import { DatabaseSync } from "node:sqlite";
import fs from "node:fs";
const f = fs.readdirSync(".devdata").filter(n => n.endsWith(".db") || n.endsWith(".sqlite"));
console.log("db files:", f.join(", "));
const db = new DatabaseSync(".devdata/" + f[0]);
const t = db.prepare("SELECT id,title,subtitle,start_date,end_date,visibility FROM trips").all();
console.log("trips:", JSON.stringify(t, null, 1));
const p = db.prepare("SELECT id,trip_id,lat,lng,place,caption,shot_at,width,height,key_thumb,key_web,visibility FROM photos").all();
console.log("photos:", JSON.stringify(p, null, 1));
const b = db.prepare("SELECT key, part, type, bytes, length(data) AS len FROM blobs ORDER BY key, part").all();
console.log("blobs count:", b.length);
console.log(JSON.stringify(b.slice(0, 12), null, 1));
